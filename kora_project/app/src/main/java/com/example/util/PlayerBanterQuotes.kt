package com.example.util

import kotlin.random.Random

/**
 * =====================================================================================
 *  رسائل كوميدية عشوائية (بالعامية المصرية) - تظهر في شاشة تشكيل الفريقين
 * =====================================================================================
 * لما الأدمن ينقل لاعب من فريق للتاني (يشيله من مكانه ويحط لاعب تاني مكانه)، بيظهر
 * كارت كوميدي صغير كأنه "كلام" اللاعب اللي اتنقل، فيه أفيه أو شكوى مضحكة. الهدف إضافة
 * روح خفيفة ومرحة للتطبيق أثناء ترتيب الفرق، مش أي حاجة جدية.
 *
 * الجمل مقسّمة نوعين:
 * - جمل ثابتة (staticQuotes): جاهزة زي ما هي.
 * - جمل بها اسم لاعب متغيّر (templatedQuotes): فيها %s بيتحط مكانها اسم لاعب عشوائي
 *   تاني من نفس المباراة (غير اللاعب اللي بيتكلم نفسه)، زي "لاعبني في أي فريق المهم
 *   بعيد عن X".
 */
object PlayerBanterQuotes {

    private val staticQuotes = listOf(
        "ياعم سيبني، الفريق ده عاجبني! 😤",
        "كل مرة.. كل مرة تغيّرني أنا.. ليه؟! 😭",
        "ما تغيّر حد غيري يا نجم 🙄",
        "أنا عايز ألعب هنا، مش عايز أخسر! 😂",
        "طب ليه أنا بالذات؟! 🥲",
        "خلاص يا كبير، أنا هعتزل من الفريق ده النهارده 🚶‍♂️",
        "يا رب يجيلك مدرب زيّي بالظبط يوم! 😏",
        "أنا مش كورة تتقل بيها إزاي ما تحب! ⚽😅",
        "طيب ما تسيبني أشجع بس، مش هلعب أصلاً؟ 🥹",
        "خليها على الله يا مدرب.. بس متنساش الحسبة! 💰😂",
        "أنا لسه واقف صح، بتنقلني ليه؟! 🧍‍♂️",
        "معلش بس أنا كنت بدأت أنسجم مع الفريق ده 🙃",
        "الظلم ده بينك وبين ربنا يا مدرب 😩",
        "طب سيبوني أشوف الديربي على الأقل من هنا 🥲",
        "أنا مش هغضب، بس هلعب وحش عمدًا 😤😂"
    )

    private val templatedQuotes = listOf(
        "لاعبني في أي فريق، المهم بعيد عن %s! 😆",
        "حط جمبي أي حد، بس مش %s ده يا خويا! 🙅‍♂️",
        "مفيش مشكلة أتنقل، بس بعيد عن %s نفسي! 😤",
        "أي حاجة إلا أكون في فريق %s تاني! 😩",
        "أخيرًا هربت من %s.. بس ليه في فريق تاني برضو؟! 😂"
    )

    /**
     * @param otherPlayerNames أسماء (أو ألقاب) باقي اللاعبين في نفس المباراة، عشان
     * نختار منهم اسم عشوائي للجمل اللي محتاجة اسم لاعب (templatedQuotes). لو القائمة
     * فاضية، بيتم اختيار جملة ثابتة بس.
     */
    fun randomQuote(otherPlayerNames: List<String>): String {
        val canUseTemplated = otherPlayerNames.isNotEmpty()
        val useTemplated = canUseTemplated && Random.nextBoolean()
        return if (useTemplated) {
            val template = templatedQuotes.random()
            val name = otherPlayerNames.random()
            template.format(name)
        } else {
            staticQuotes.random()
        }
    }
}
